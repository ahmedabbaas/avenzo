import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const postcss = createRequire(require.resolve("next/package.json"))("postcss");

const css = await readFile("app/avenzo-2.1.css", "utf8");
const root = postcss.parse(css);
assert.ok(root.nodes.some(node => node.type === "atrule" && node.name === "layer" && node.params === "avenzo-21"));
assert.match(css, /--accent:\s*#d2d7dd/i, "canonical accent must be silver");
assert.match(css, /--av-violet:\s*#d2d7dd/i, "legacy token names must resolve to metallic accent");
assert.match(css, /html\[data-theme="light"\] \.social-app/);
assert.match(css, /prefers-reduced-motion:\s*reduce/);
assert.match(css, /min-width:\s*44px/);
assert.doesNotMatch(css, /#c6ff45|#d8ff80|#57751b|#3f5910|rgba\(198,\s*255,\s*69|rgba\(87,\s*117,\s*27/i, "old lime/olive values must not remain");
assert.match(css, /AVENZO PREMIUM UI/);
assert.match(css, /--avenzo-premium-duration/);
assert.match(css, /:active/);
assert.match(css, /:focus-visible/);
console.log("AVENZO Premium UI checks passed: Obsidian Chrome palette, light theme, reduced motion, touch targets, and interaction states.");
